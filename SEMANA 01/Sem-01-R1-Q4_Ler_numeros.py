#Enunciado
'''
Crie um programa que leia dois números e mostre a soma entre eles
'''

# Entrada de dados
a = float(input("Digite o primeiro número: "))
b = float(input("Digite o segundo número: "))

# Processamento
soma = a + b

# Saída de dados
print(f"A soma entre {a:.2f} e {b:.2f} é {soma:.2f}")
